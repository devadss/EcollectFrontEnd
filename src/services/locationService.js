let apiStatesCache = null;

export const fetchStatesList = async () => {
  if (apiStatesCache && apiStatesCache.length > 0) {
    return apiStatesCache;
  }

  try {
    const response = await fetch('https://cdn-api.co-vin.in/api/v2/admin/location/states', {
      method: 'GET',
      headers: { 'Accept-Language': 'en_US' }
    });

    if (response.ok) {
      const data = await response.json();
      if (data && Array.isArray(data.states) && data.states.length > 0) {
        const fetched = data.states.map(s => s.state_name);
        apiStatesCache = fetched;
        return fetched;
      }
    }
  } catch (err) {
    console.warn('API fetch for states failed, using built-in states repository:', err);
  }

  apiStatesCache = Object.keys(INDIA_STATES_AND_DISTRICTS);
  return apiStatesCache;
};

export const getAllStates = () => {
  return Object.keys(INDIA_STATES_AND_DISTRICTS);
};

export const getDistrictsByState = (stateName) => {
  if (!stateName) return [];
  
  const trimmed = stateName.trim().toLowerCase();
  
  for (const [state, districts] of Object.entries(INDIA_STATES_AND_DISTRICTS)) {
    if (state.toLowerCase() === trimmed || state.toLowerCase().includes(trimmed) || trimmed.includes(state.toLowerCase())) {
      return districts;
    }
  }

  return [];
};

export const lookupLocationByPincode = async (pincode) => {
  if (!pincode || pincode.toString().trim().length !== 6) return null;
  
  try {
    const res = await fetch(`https://api.postalpincode.in/pincode/${pincode.toString().trim()}`);
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data[0]?.Status === 'Success' && data[0]?.PostOffice?.length > 0) {
        const postOffice = data[0].PostOffice[0];
        return {
          state: postOffice.State,
          district: postOffice.District,
          city: postOffice.District,
          taluk: postOffice.Block || postOffice.Taluk || postOffice.Name,
          pincode: pincode.toString().trim()
        };
      }
    }
  } catch (err) {
    console.warn('Pincode lookup error:', err);
  }

  return null;
};
